import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const manifestPath = path.join(root, 'tooling/icons/manifest.json');
const outputDir = path.join(root, 'packages/ui/src/icons');

const SHAPE_TAGS = new Set(['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);

function attr(attributes, name) {
  const match = attributes.match(new RegExp(`${name}="([^"]*)"`));
  return match === null ? null : match[1];
}

function toNumber(value) {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : null;
}

/** Converts iconify SVG markup into a serialisable shape list for react-native-svg. */
function parseBody(body) {
  const shapes = [];
  const tagPattern = /<(\w+)([^>]*)\/?>/g;

  for (const match of body.matchAll(tagPattern)) {
    const [, tag, attributes] = match;
    if (tag === undefined || attributes === undefined || !SHAPE_TAGS.has(tag)) {
      continue;
    }

    if (tag === 'path') {
      shapes.push({ tag, d: attr(attributes, 'd') });
      continue;
    }
    if (tag === 'circle') {
      shapes.push({
        tag,
        cx: toNumber(attr(attributes, 'cx')),
        cy: toNumber(attr(attributes, 'cy')),
        r: toNumber(attr(attributes, 'r')),
      });
      continue;
    }
    if (tag === 'ellipse') {
      shapes.push({
        tag,
        cx: toNumber(attr(attributes, 'cx')),
        cy: toNumber(attr(attributes, 'cy')),
        rx: toNumber(attr(attributes, 'rx')),
        ry: toNumber(attr(attributes, 'ry')),
      });
      continue;
    }
    if (tag === 'rect') {
      shapes.push({
        tag,
        x: toNumber(attr(attributes, 'x')),
        y: toNumber(attr(attributes, 'y')),
        width: toNumber(attr(attributes, 'width')),
        height: toNumber(attr(attributes, 'height')),
        rx: toNumber(attr(attributes, 'rx')),
      });
      continue;
    }
    if (tag === 'line') {
      shapes.push({
        tag,
        x1: toNumber(attr(attributes, 'x1')),
        y1: toNumber(attr(attributes, 'y1')),
        x2: toNumber(attr(attributes, 'x2')),
        y2: toNumber(attr(attributes, 'y2')),
      });
      continue;
    }
    shapes.push({ tag, points: attr(attributes, 'points') });
  }

  return shapes;
}

async function loadIconSet(setName) {
  const iconsPath = require.resolve(`@iconify-json/${setName}/icons.json`);
  return JSON.parse(await readFile(iconsPath, 'utf8'));
}

async function main() {
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  const entries = [];

  for (const [setName, names] of Object.entries(manifest.sets)) {
    const iconSet = await loadIconSet(setName);
    for (const name of names) {
      const icon = iconSet.icons[name] ?? iconSet.aliases?.[name];
      if (icon === undefined) {
        throw new Error(`Unknown icon ${setName}:${name}`);
      }
      const body = icon.body ?? iconSet.icons[icon.parent]?.body;
      if (typeof body !== 'string') {
        throw new Error(`Icon ${setName}:${name} has no inline body`);
      }
      const [width, height] = String(icon.width ?? iconSet.width ?? 24)
        .split('x')
        .map(Number);
      entries.push({
        key: name,
        width: width ?? 24,
        height: height ?? 24,
        shapes: parseBody(body),
      });
    }
  }

  entries.sort((a, b) => a.key.localeCompare(b.key));

  const generated = [
    '// Generated by tooling/icons/build-icons.mjs. Do not edit by hand.',
    "import type { IconShapes } from './types';",
    '',
    'export const lucideIcons = {',
    ...entries.map(
      (entry) =>
        `  '${entry.key}': { width: ${entry.width}, height: ${entry.height}, shapes: ${JSON.stringify(entry.shapes)} },`,
    ),
    '} as const satisfies Record<string, IconShapes>;',
    '',
    'export type IconName = keyof typeof lucideIcons;',
    '',
    'export const ICON_NAMES = Object.keys(lucideIcons) as IconName[];',
    '',
  ].join('\n');

  await mkdir(outputDir, { recursive: true });
  await writeFile(path.join(outputDir, 'lucide.generated.ts'), generated, 'utf8');
  process.stdout.write(`Generated ${entries.length} icons\n`);
}

await main();
