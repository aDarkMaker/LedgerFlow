import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const migrationDir = path.join(root, 'packages/db/drizzle');
const journalPath = path.join(migrationDir, 'meta/_journal.json');
const outputPath = path.join(root, 'packages/db/src/migrations.generated.ts');

// Metro cannot import .sql, so every journal entry is inlined as a named string.
const journal = JSON.parse(await readFile(journalPath, 'utf8'));

const parts = [];
const keys = [];
for (const entry of journal.entries) {
  const sql = await readFile(path.join(migrationDir, `${entry.tag}.sql`), 'utf8');
  const escaped = sql.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${');
  const key = `m${String(entry.idx).padStart(4, '0')}`;
  parts.push(`const ${key} = \`${escaped}\`;`);
  keys.push(key);
}

const output = `// Generated by tooling/migrations/build-migrations.mjs. Do not edit by hand.
import type { MigrationBundle } from './migrations.types';

const journal: MigrationBundle['journal'] = ${JSON.stringify(journal, null, 2)};

${parts.join('\n\n')}

export const migrationBundle: MigrationBundle = {
  journal,
  migrations: { ${keys.join(', ')} },
};
`;

await writeFile(outputPath, output, 'utf8');
process.stdout.write(`Wrote ${path.relative(root, outputPath)}\n`);
