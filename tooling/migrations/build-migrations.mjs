import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const sqlPath = path.join(root, 'packages/db/drizzle/0000_init.sql');
const journalPath = path.join(root, 'packages/db/drizzle/meta/_journal.json');
const outputPath = path.join(root, 'packages/db/src/migrations.generated.ts');

// Metro cannot import .sql, so the generated statement bundle is inlined as a string.
const sql = await readFile(sqlPath, 'utf8');
const journal = JSON.parse(await readFile(journalPath, 'utf8'));

const escaped = sql.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${');

const output = `// Generated by tooling/migrations/build-migrations.mjs. Do not edit by hand.
import type { MigrationBundle } from './migrations.types';

const journal: MigrationBundle['journal'] = ${JSON.stringify(journal, null, 2)};

const m0000 = \`${escaped}\`;

export const migrationBundle: MigrationBundle = { journal, migrations: { m0000 } };
`;

await writeFile(outputPath, output, 'utf8');
process.stdout.write(`Wrote ${path.relative(root, outputPath)}\n`);
